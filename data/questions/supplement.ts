import type { InterviewQuestion, QuestionCategory, QuestionDifficulty } from "../../types/interview";

type ConceptEntry = {
  id: string;
  category: QuestionCategory;
  difficulty: QuestionDifficulty;
  tags: string[];
  score: number;
  titleRu: string;
  titleEn: string;
  answerRu: string;
  answerEn: string;
  detailRu: string;
  detailEn: string;
  followRu: string;
  followEn: string;
  followAnswerRu: string;
  followAnswerEn: string;
  keywords: string[];
};

const expectations = {
  ru: ["Коротко объяснить суть.", "Связать ответ с фронтенд-практикой.", "Назвать ограничение или trade-off."],
  en: ["Explain the core idea shortly.", "Connect the answer to frontend practice.", "Mention a limitation or trade-off."]
};

const mistakes = {
  ru: ["Уйти в длинную теорию.", "Не привести практический пример.", "Перепутать похожие понятия."],
  en: ["Going into long theory.", "Not giving a practical example.", "Confusing similar concepts."]
};

function concept(entry: ConceptEntry): InterviewQuestion {
  return {
    id: entry.id,
    category: entry.category,
    difficulty: entry.difficulty,
    tags: entry.tags,
    frequencyScore: entry.score,
    question: {
      ru: entry.titleRu.endsWith("?") ? entry.titleRu : `Что такое ${entry.titleRu}?`,
      en: entry.titleEn.endsWith("?") ? entry.titleEn : `What is ${entry.titleEn}?`
    },
    shortAnswer: { ru: entry.answerRu, en: entry.answerEn },
    detailedAnswer: { ru: entry.detailRu, en: entry.detailEn },
    followUpQuestion: { ru: entry.followRu, en: entry.followEn },
    followUpAnswer: { ru: entry.followAnswerRu, en: entry.followAnswerEn },
    interviewerExpectation: expectations,
    commonMistakes: mistakes,
    keywords: entry.keywords,
    relatedQuestions: []
  };
}

